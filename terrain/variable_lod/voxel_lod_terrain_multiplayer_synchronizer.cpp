VoxelLodTerrainMultiplayerSynchronizer::VoxelLodTerrainMultiplayerSynchronizer() {
	Dictionary config;
	config["rpc_mode"] = MultiplayerAPI::RPC_MODE_AUTHORITY;
	config["transfer_mode"] = MultiplayerPeer::TRANSFER_MODE_RELIABLE;
	config["call_local"] = false;
	config["channel"] = _rpc_channel;

	rpc_config(VoxelStringNames::get_singleton()._rpc_receive_blocks, config);
	rpc_config(VoxelStringNames::get_singleton()._rpc_receive_area, config);

	// The repair channel is the one message that travels client -> server, so it is the only one configured for ANY
	// peer. Everything it can produce is bounded by `_b_request_blocks`, which answers only with blocks the asking
	// peer's own viewer already covers.
	Dictionary request_config;
	request_config["rpc_mode"] = MultiplayerAPI::RPC_MODE_ANY_PEER;
	request_config["transfer_mode"] = MultiplayerPeer::TRANSFER_MODE_RELIABLE;
	request_config["call_local"] = false;
	request_config["channel"] = _rpc_channel;
	rpc_config(VoxelStringNames::get_singleton()._rpc_request_blocks, request_config);

	set_process(true);
}

bool VoxelLodTerrainMultiplayerSynchronizer::is_server() const {
	ZN_ASSERT_RETURN_V(is_inside_tree(), false);
	// Note, when using multiple Multiplayer branches in the scene tree, `get_multiplayer` can be significantly slower,
	// because it involves constructing a NodePath and then querying a HashMap<NodePah,V> to check which nodes have
	// custom multiplayer. In cases Godot thought of, this is not a big issue, but in our case this can have a
	// noticeable impact because `is_server()` can be called a thousand times in a frame when a viewer joins or
	// teleports.
	Ref<MultiplayerAPI> mp = get_multiplayer();
	ZN_ASSERT_RETURN_V(mp.is_valid(), false);
	return mp->is_server();
}

void VoxelLodTerrainMultiplayerSynchronizer::send_block(
		int viewer_peer_id,
		const VoxelBuffer *voxels,
		Vector3i bpos,
		unsigned int lod_index
) {
	ZN_PROFILE_SCOPE();

	// A size of zero means the block has no voxel data (it can be procedurally generated by the client).
	// Note: the span references a thread-local buffer, which remains valid until the next serialization happening in
	// this thread. We copy it into the message right away.
	Span<const uint8_t> voxel_data;
	if (voxels != nullptr) {
		BlockSerializer::SerializeResult result =
				BlockSerializer::serialize_and_compress(*voxels, CompressedData::COMPRESSION_LZ4);
		ZN_ASSERT_RETURN(result.success);
		voxel_data = to_span(result.data);
	}
	const size_t voxel_data_size = voxel_data.size();

	PackedByteArray message_data;
	message_data.resize(3 * sizeof(int16_t) + sizeof(uint8_t) + sizeof(uint16_t) + voxel_data_size);

	ByteSpanWithPosition mw_span(Span<uint8_t>(message_data.ptrw(), message_data.size()), 0);
	MemoryWriterExistingBuffer mw(mw_span, ENDIANNESS_LITTLE_ENDIAN);

	mw.store_16(bpos.x);
	mw.store_16(bpos.y);
	mw.store_16(bpos.z);
	mw.store_8(lod_index);
	ZN_ASSERT_RETURN(voxel_data_size <= 65535);
	mw.store_16(voxel_data_size);
	if (voxel_data_size > 0) {
		mw.store_buffer(voxel_data);
	}

	// Instead of sending it right away, defer it until the terrain finished processing. Sending individual blocks with
	// the RPC system is too slow.
	_deferred_block_messages_per_peer[viewer_peer_id].push_back(DeferredBlockMessage{ message_data });
}

void VoxelLodTerrainMultiplayerSynchronizer::send_area(Box3i voxel_box) {
	_pending_area_boxes.push_back(PendingArea{ voxel_box, _edit_source_peer_id });
}

void VoxelLodTerrainMultiplayerSynchronizer::set_edit_source_peer_id(int peer_id) {
	_edit_source_peer_id = peer_id;
}

int VoxelLodTerrainMultiplayerSynchronizer::get_edit_source_peer_id() const {
	return _edit_source_peer_id;
}

void VoxelLodTerrainMultiplayerSynchronizer::flush_pending_areas() {
	if (_pending_area_boxes.size() == 0) {
		return;
	}
	ZN_PROFILE_SCOPE();

	static thread_local StdVector<PendingArea> tls_merged_boxes;
	StdVector<PendingArea> &merged_boxes = tls_merged_boxes;
	merged_boxes.clear();

	for (const PendingArea &pending : _pending_area_boxes) {
		bool did_merge = false;

		for (PendingArea &merged : merged_boxes) {
			// Only merge edits from the same source, otherwise merging would decide for both who receives them
			if (merged.source_peer_id != pending.source_peer_id) {
				continue;
			}

			Box3i candidate = merged.box;
			candidate.merge_with(pending.box);

			const uint64_t candidate_volume = Vector3iUtil::get_volume_u64(candidate.size);
			const uint64_t separate_volume =
					Vector3iUtil::get_volume_u64(merged.box.size) + Vector3iUtil::get_volume_u64(pending.box.size);

			// Merge when one message doesn't cost much more than two. Successive applications of a brush overlap
			// heavily, so a whole stroke within a frame collapses into a single message, while edits made far apart
			// stay separate instead of sending everything in between.
			if (candidate_volume <= separate_volume * 2 && candidate_volume <= MAX_MERGED_AREA_VOLUME) {
				merged.box = candidate;
				did_merge = true;
				break;
			}
		}

		if (!did_merge) {
			merged_boxes.push_back(pending);
		}
	}

	ZN_PRINT_VERBOSE(
			format("MP server flushing {} edited boxes as {} messages", _pending_area_boxes.size(), merged_boxes.size())
	);
	_pending_area_boxes.clear();

	for (const PendingArea &merged : merged_boxes) {
		send_area_immediate(merged.box, merged.source_peer_id);
	}
}

void VoxelLodTerrainMultiplayerSynchronizer::send_area_immediate(Box3i voxel_box, int excluded_peer_id) {
	ZN_PROFILE_SCOPE();
	ZN_ASSERT_RETURN(_terrain != nullptr);

	StdVector<ViewerID> viewers;
	_terrain->get_viewers_in_area(viewers, voxel_box);

	ZN_PRINT_VERBOSE(format("MP server send_area {} viewers {}", voxel_box, viewers.size()));

	if (viewers.size() == 0) {
		return;
	}

	// Not particularly efficient for single-voxel edits, but should scale ok with bigger boxes
	VoxelBuffer voxels(VoxelBuffer::ALLOCATOR_POOL);
	voxels.create(voxel_box.size);
	_terrain->get_storage().copy(voxel_box.position, voxels, 0xff, true);

	BlockSerializer::SerializeResult result =
			BlockSerializer::serialize_and_compress(voxels, CompressedData::COMPRESSION_LZ4);
	ZN_ASSERT_RETURN(result.success);

	PackedByteArray pba;
	pba.resize(4 * sizeof(int32_t) + result.data.size());

	ByteSpanWithPosition mw_span(Span<uint8_t>(pba.ptrw(), pba.size()), 0);
	MemoryWriterExistingBuffer mw(mw_span, ENDIANNESS_LITTLE_ENDIAN);

	mw.store_32(voxel_box.position.x);
	mw.store_32(voxel_box.position.y);
	mw.store_32(voxel_box.position.z);
	mw.store_32(result.data.size());
	mw.store_buffer(to_span(result.data));

	for (const ViewerID viewer_id : viewers) {
		const int peer_id = VoxelEngine::get_singleton().get_viewer_network_peer_id(viewer_id);
		if (peer_id != -1 && peer_id != MultiplayerPeer::TARGET_PEER_SERVER && peer_id != excluded_peer_id) {
			rpc_id(peer_id, VoxelStringNames::get_singleton()._rpc_receive_area, pba);
		}
	}
}

void VoxelLodTerrainMultiplayerSynchronizer::_notification(int p_what) {
	if (p_what == NOTIFICATION_PARENTED) {
		VoxelLodTerrain *terrain = Object::cast_to<VoxelLodTerrain>(get_parent());
		if (terrain != nullptr && terrain->get_multiplayer_synchronizer() == nullptr) {
			terrain->set_multiplayer_synchronizer(this);
			_terrain = terrain;
		}

	} else if (p_what == NOTIFICATION_UNPARENTED) {
		if (_terrain != nullptr && _terrain->get_multiplayer_synchronizer() == this) {
			_terrain->set_multiplayer_synchronizer(nullptr);
		}
		_terrain = nullptr;

	} else if (p_what == NOTIFICATION_PROCESS) {
		process();
	}
}

void VoxelLodTerrainMultiplayerSynchronizer::process() {
	ZN_PROFILE_SCOPE();

	flush_pending_areas();

	if (_terrain != nullptr && is_inside_tree() && !is_server()) {
		process_block_repair_requests();
	}

	for (auto it = _deferred_block_messages_per_peer.begin(); it != _deferred_block_messages_per_peer.end(); ++it) {
		StdVector<DeferredBlockMessage> &messages = it->second;

		if (messages.size() == 0) {
			continue;
		}

		PackedByteArray pba;
		// Make one big fat message per frame per peer, because sending many is super-slow with Godot's ENet multiplayer
		// integration. It calls flush() on every RPC and that takes a lot of time, and there is overhead caused by
		// the high-level features...

		unsigned int size = 0;
		for (const DeferredBlockMessage &message : messages) {
			size += message.data.size();
		}

		pba.resize(1 * sizeof(uint32_t) + size);

		ByteSpanWithPosition mw_span(Span<uint8_t>(pba.ptrw(), pba.size()), 0);
		MemoryWriterExistingBuffer mw(mw_span, ENDIANNESS_LITTLE_ENDIAN);
		mw.store_32(messages.size());

		for (const DeferredBlockMessage &message : messages) {
			mw.store_buffer(Span<const uint8_t>(message.data.ptr(), message.data.size()));
		}
		ZN_ASSERT(mw.data.size() == mw.data.pos);

		messages.clear();

		const int peer_id = it->first;
		ZN_PRINT_VERBOSE(format("Sending {} bytes of LOD block data to peer {}", pba.size(), peer_id));
		rpc_id(peer_id, VoxelStringNames::get_singleton()._rpc_receive_blocks, pba);
	}
}

void VoxelLodTerrainMultiplayerSynchronizer::_b_receive_blocks(PackedByteArray message_data) {
	ZN_PROFILE_SCOPE();
	ZN_ASSERT_RETURN(_terrain != nullptr);

	MemoryReader mr(Span<const uint8_t>(message_data.ptr(), message_data.size()), ENDIANNESS_LITTLE_ENDIAN);

	const unsigned int block_count = mr.get_32();

	ZN_PRINT_VERBOSE(format("MP client receive_blocks count {}", block_count));

	for (unsigned int i = 0; i < block_count; ++i) {
		Vector3i bpos;
		// This effectively limits volume size per LOD to 1,048,576 voxels. If really required, we could double this
		// data to cover more.
		bpos.x = int16_t(mr.get_16());
		bpos.y = int16_t(mr.get_16());
		bpos.z = int16_t(mr.get_16());
		const unsigned int lod_index = mr.get_8();
		const int voxel_data_size = mr.get_16();

		std::shared_ptr<VoxelBuffer> voxels_p = nullptr;

		if (voxel_data_size > 0) {
			VoxelBuffer voxels(VoxelBuffer::ALLOCATOR_POOL);
			ZN_ASSERT_RETURN(
					BlockSerializer::decompress_and_deserialize(mr.data.sub(mr.pos, voxel_data_size), voxels)
			);

			voxels_p = make_shared_instance<VoxelBuffer>(VoxelBuffer::ALLOCATOR_POOL);
			*voxels_p = std::move(voxels);
		}

		mr.pos += voxel_data_size;

		ZN_ASSERT_RETURN(_terrain != nullptr);
		_terrain->try_set_block_data(bpos, lod_index, voxels_p);
	}
}

void VoxelLodTerrainMultiplayerSynchronizer::_b_receive_area(PackedByteArray message_data) {
	ZN_PROFILE_SCOPE();
	ZN_ASSERT_RETURN(_terrain != nullptr);

	MemoryReader mr(Span<const uint8_t>(message_data.ptr(), message_data.size()), ENDIANNESS_LITTLE_ENDIAN);

	Vector3i pos;
	pos.x = int32_t(mr.get_32());
	pos.y = int32_t(mr.get_32());
	pos.z = int32_t(mr.get_32());
	const int voxel_data_size = mr.get_32();

	VoxelBuffer voxels(VoxelBuffer::ALLOCATOR_POOL);
	ZN_ASSERT_RETURN(BlockSerializer::decompress_and_deserialize(mr.data.sub(mr.pos, voxel_data_size), voxels));

	const Box3i voxel_box(pos, voxels.get_size());
	ZN_PRINT_VERBOSE(format("MP client receive_area {}", voxel_box));
	VoxelData &data = _terrain->get_storage();

	// Unedited blocks on the client usually have no voxel data (they are generated on the fly for meshing), and
	// `paste` only writes into blocks that have voxels. Materialize generator output in the area first, like local
	// edits do.
	data.pre_generate_box(voxel_box);

	// If the incoming state is what we already have, applying it would schedule a redundant remesh of every
	// affected LOD, which is by far the expensive part. This is the common case when the client predicts its own
	// edits locally: the prediction runs the same deterministic operation on the same data as the server, so the
	// authoritative answer usually confirms it exactly.
	{
		ZN_PROFILE_SCOPE_NAMED("Compare with local state");
		VoxelBuffer current(VoxelBuffer::ALLOCATOR_POOL);
		current.create(voxels.get_size());
		data.copy(pos, current, 0xff, true);
		if (current.equals(voxels)) {
			ZN_PRINT_VERBOSE(format("MP client receive_area {} already matches local state", voxel_box));
			return;
		}
	}

	data.paste(pos, voxels, 0xff, false, true);

	_terrain->post_edit_area(
			voxel_box,
			// Don't bother for now, update mesh regardless. If necessary we would have to add a flag with the message
			// to tell it's not actually changing voxels (if it's metadata changes), but might not be worth it
			true
	);

	// Tell game code the authoritative state of this area just replaced whatever was here. Clients predicting their
	// own edits need this: the incoming state reflects what the server had when it sent it, so any edit made locally
	// since then was just overwritten and has to be applied again.
	emit_signal("area_received", voxel_box.position, voxel_box.size);
}

void VoxelLodTerrainMultiplayerSynchronizer::process_block_repair_requests() {
	ZN_PROFILE_SCOPE();
	ZN_ASSERT_RETURN(_terrain != nullptr);

	const uint64_t now = Time::get_singleton()->get_ticks_msec();
	if (now < _next_repair_request_msec) {
		return;
	}

	static thread_local StdVector<VoxelLodTerrainUpdateData::BlockLocation> tls_missing;
	tls_missing.clear();
	_terrain->get_missing_data_blocks_for_local_viewers(tls_missing, MAX_TRACKED_MISSING_BLOCKS);

	const unsigned int total_missing = tls_missing.size();

	if (total_missing == 0) {
		// Steady state: nothing is missing, so nothing is sent and the timer goes back to being responsive.
		_repair_request_interval_msec = MIN_REPAIR_REQUEST_INTERVAL_MSEC;
		_last_missing_block_count = 0;
		_repair_scan_cursor = 0;
		_next_repair_request_msec = now + MIN_REPAIR_REQUEST_INTERVAL_MSEC;
		return;
	}

	bool any_lod0_missing = false;
	for (const VoxelLodTerrainUpdateData::BlockLocation &loc : tls_missing) {
		if (loc.lod == 0) {
			any_lod0_missing = true;
			break;
		}
	}
	const uint64_t max_interval =
			any_lod0_missing ? MAX_REPAIR_REQUEST_INTERVAL_LOD0_MSEC : MAX_REPAIR_REQUEST_INTERVAL_MSEC;

	// Progress is "the hole got smaller", measured on the whole hole. While it is shrinking, keep asking at full
	// rate; once it stops, slow down and start rotating through the set so a stuck prefix cannot starve the rest.
	const bool made_progress = _last_missing_block_count == 0 || total_missing < _last_missing_block_count;
	if (made_progress) {
		_repair_request_interval_msec = MIN_REPAIR_REQUEST_INTERVAL_MSEC;
		_repair_scan_cursor = 0;
	} else {
		_repair_request_interval_msec = math::min(_repair_request_interval_msec * 2, max_interval);
		_repair_scan_cursor += MAX_REQUESTED_BLOCKS_PER_MESSAGE;
	}
	_repair_request_interval_msec = math::min(_repair_request_interval_msec, max_interval);
	_last_missing_block_count = total_missing;
	_next_repair_request_msec = now + _repair_request_interval_msec;

	if (_repair_scan_cursor >= total_missing) {
		_repair_scan_cursor = 0;
	}
	const unsigned int count = math::min(total_missing - _repair_scan_cursor, MAX_REQUESTED_BLOCKS_PER_MESSAGE);

	PackedByteArray message_data;
	message_data.resize(sizeof(uint16_t) + count * (3 * sizeof(int16_t) + sizeof(uint8_t)));

	ByteSpanWithPosition mw_span(Span<uint8_t>(message_data.ptrw(), message_data.size()), 0);
	MemoryWriterExistingBuffer mw(mw_span, ENDIANNESS_LITTLE_ENDIAN);

	mw.store_16(count);
	for (unsigned int i = 0; i < count; ++i) {
		const VoxelLodTerrainUpdateData::BlockLocation &loc = tls_missing[_repair_scan_cursor + i];
		mw.store_16(loc.position.x);
		mw.store_16(loc.position.y);
		mw.store_16(loc.position.z);
		mw.store_8(loc.lod);
	}

	ZN_PRINT_VERBOSE(
			format("MP client requesting {} of {} missing data blocks", count, total_missing)
	);
	rpc_id(
			MultiplayerPeer::TARGET_PEER_SERVER,
			VoxelStringNames::get_singleton()._rpc_request_blocks,
			message_data
	);
}

void VoxelLodTerrainMultiplayerSynchronizer::_b_request_blocks(PackedByteArray message_data) {
	ZN_PROFILE_SCOPE();
	ZN_ASSERT_RETURN(_terrain != nullptr);
	if (!is_server()) {
		// A client has no business answering these, and pretending otherwise would let peers talk to each other
		// through us.
		return;
	}

	Ref<MultiplayerAPI> mp = get_multiplayer();
	ZN_ASSERT_RETURN(mp.is_valid());
	const int peer_id = mp->get_remote_sender_id();
	if (peer_id <= MultiplayerPeer::TARGET_PEER_SERVER) {
		return;
	}

	const uint64_t now = Time::get_singleton()->get_ticks_msec();

	// Occasionally forget peers that have gone quiet, so a server running for a long time doesn't accumulate a
	// budget entry per peer that ever connected.
	if (now - _last_repair_budget_cleanup_msec > 60'000) {
		_last_repair_budget_cleanup_msec = now;
		for (auto it = _repair_budget_per_peer.begin(); it != _repair_budget_per_peer.end();) {
			it = (now - it->second.last_request_msec > 60'000) ? _repair_budget_per_peer.erase(it) : ++it;
		}
	}

	RepairBudget &budget = _repair_budget_per_peer[peer_id];

	// Rate gate first, and before parsing anything: flooding must cost the server a map lookup and a comparison,
	// not a message walk.
	if (budget.last_request_msec != 0 && now - budget.last_request_msec < MIN_REQUEST_INTERVAL_MSEC) {
		return;
	}
	budget.last_request_msec = now;

	if (now - budget.window_start_msec >= 1000) {
		budget.window_start_msec = now;
		budget.blocks_in_window = 0;
	}
	if (budget.blocks_in_window >= MAX_REPAIRED_BLOCKS_PER_SECOND) {
		return;
	}

	if (message_data.size() < static_cast<int>(sizeof(uint16_t))) {
		return;
	}

	MemoryReader mr(Span<const uint8_t>(message_data.ptr(), message_data.size()), ENDIANNESS_LITTLE_ENDIAN);
	unsigned int count = mr.get_16();

	// Trusting the declared count against the actual buffer, not the other way around.
	constexpr unsigned int entry_size = 3 * sizeof(int16_t) + sizeof(uint8_t);
	const unsigned int available = (message_data.size() - sizeof(uint16_t)) / entry_size;
	count = math::min(count, available);
	count = math::min(count, MAX_REQUESTED_BLOCKS_PER_MESSAGE);

	unsigned int sent = 0;
	for (unsigned int i = 0; i < count; ++i) {
		Vector3i bpos;
		bpos.x = int16_t(mr.get_16());
		bpos.y = int16_t(mr.get_16());
		bpos.z = int16_t(mr.get_16());
		const unsigned int lod_index = mr.get_8();

		if (budget.blocks_in_window >= MAX_REPAIRED_BLOCKS_PER_SECOND) {
			break;
		}
		// THE authority check: a peer only ever gets blocks its own server-side viewer already covers, which is
		// exactly the set the server would have pushed to it unprompted. This is what makes the channel safe to
		// expose — the worst a hostile client achieves is receiving its own terrain twice.
		if (!_terrain->is_data_block_in_peer_view(peer_id, bpos, lod_index)) {
			continue;
		}
		if (_terrain->resend_data_block_to_peer(peer_id, bpos, lod_index)) {
			++budget.blocks_in_window;
			++sent;
		}
	}

	if (sent > 0) {
		ZN_PRINT_VERBOSE(format("MP server repaired {} data blocks for peer {}", sent, peer_id));
	}
}

void VoxelLodTerrainMultiplayerSynchronizer::_b_force_resync_area(Vector3i origin, Vector3i size) {
	ZN_ASSERT_RETURN(_terrain != nullptr);
	if (!is_server()) {
		return;
	}
	// Always goes to everyone, including whoever asked: this exists to correct a client, so it must reach it
	const int previous_source = _edit_source_peer_id;
	_edit_source_peer_id = 0;
	send_area(Box3i(origin, size));
	_edit_source_peer_id = previous_source;
}

