void VoxelLodTerrainMultiplayerSynchronizer::_bind_methods() {
	// TODO These methods are not supposed to be exposed. They only exist for Godot's high-level multiplayer to find
	// them.
	ClassDB::bind_method(
			D_METHOD("_rpc_receive_blocks", "data"), &VoxelLodTerrainMultiplayerSynchronizer::_b_receive_blocks
	);
	ClassDB::bind_method(
			D_METHOD("_rpc_receive_area", "data"), &VoxelLodTerrainMultiplayerSynchronizer::_b_receive_area
	);
	ClassDB::bind_method(
			D_METHOD("_rpc_request_blocks", "data"), &VoxelLodTerrainMultiplayerSynchronizer::_b_request_blocks
	);

	ClassDB::bind_method(D_METHOD("is_server"), &VoxelLodTerrainMultiplayerSynchronizer::is_server);
	ClassDB::bind_method(
			D_METHOD("set_edit_source_peer_id", "peer_id"),
			&VoxelLodTerrainMultiplayerSynchronizer::set_edit_source_peer_id
	);
	ClassDB::bind_method(
			D_METHOD("get_edit_source_peer_id"), &VoxelLodTerrainMultiplayerSynchronizer::get_edit_source_peer_id
	);

	// Emitted on clients after authoritative voxels from the server replaced the contents of an area. Not emitted
	// when the incoming data already matched local state, since nothing changed in that case.
	ADD_SIGNAL(MethodInfo(
			"area_received",
			PropertyInfo(Variant::VECTOR3I, "origin"),
			PropertyInfo(Variant::VECTOR3I, "size")
	));
	// Sends the current state of a voxel area to every remote viewer covering it. Useful when clients predict their
	// own edits: if the server ends up not applying a requested edit, it can call this to correct the prediction.
	ClassDB::bind_method(
			D_METHOD("force_resync_area", "origin", "size"),
			&VoxelLodTerrainMultiplayerSynchronizer::_b_force_resync_area
	);
}

